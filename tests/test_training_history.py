import unittest
from datetime import datetime, timedelta

import sync
from garmin_coach.athlete import parse_athlete_config
from garmin_coach.plan import no_active_plan

# Section names and phrases the coaching skills read by name (running-plan-design,
# running-plan-adaptation, running-intensity). Renaming one in sync.py breaks them.
SKILL_CONTRACT = [
    "## Recent Weekly Volume (last 10 weeks)",
    "## Weekly Intensity Split",
    "| From laps |",
    "Bands for this athlete's configured zones: Easy = Z1, Z2 · Moderate = Z3 · Hard = Z4, Z5",
    "## Notable Quality Sessions",
    "## Recent Long Runs",
    "## Post-Workout Self-Evaluation",
    "## Full Activity Log",
]

CONFIG = parse_athlete_config({
    "hr_zones": [("Z1", 0, 120), ("Z2", 120, 145), ("Z3", 145, 160), ("Z4", 160, 175), ("Z5", 175, 300)],
    "long_run_km": 15,
    "quality_keywords": ["Intervals"],
})


def _row(day, title, km, minutes, hr, activity_id, feeling=""):
    return {"activity_id": activity_id, "date": day.strftime("%Y-%m-%d"), "title": title,
            "distance_km": str(km), "duration_min": str(minutes), "avg_pace_min_km": "5:30",
            "avg_heart_rate": str(hr), "feeling": feeling, "perceived_effort": ""}


class TrainingHistoryContractTests(unittest.TestCase):
    def setUp(self):
        monday = datetime(2026, 3, 30)
        self.rows, self.laps = [], []
        for week in range(3):
            start = monday + timedelta(weeks=week)
            self.rows.append(_row(start, "Easy run", 8, 48, 135, f"{week}1", feeling="Normal"))
            self.rows.append(_row(start + timedelta(days=2), "Intervals 6x800", 10, 50, 162, f"{week}2"))
            self.rows.append(_row(start + timedelta(days=5), "Long run", 18, 105, 140, f"{week}3"))
            self.laps.append({"activity_id": f"{week}2", "lap_index": "0", "duration_min": "15", "avg_hr": "130"})
            self.laps.append({"activity_id": f"{week}2", "lap_index": "1", "duration_min": "20", "avg_hr": "170"})
        self.now = datetime(2026, 4, 20, 7, 0)

    def _render(self):
        return sync.render_training_history(
            self.rows, self.laps, config=CONFIG, plan=no_active_plan(),
            now=self.now, laps_csv_path="data/activity_laps.csv",
        )

    def test_sections_the_skills_read_are_present(self):
        history = self._render()
        for phrase in SKILL_CONTRACT:
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, history)

    def test_rendering_depends_only_on_its_inputs(self):
        history = self._render()

        self.assertEqual(history, self._render())
        self.assertIn("Auto-generated by sync.py on 2026-04-20 07:00", history)

    def test_no_activities_renders_nothing(self):
        self.assertIsNone(sync.render_training_history(
            [], [], config=CONFIG, plan=no_active_plan(), now=self.now, laps_csv_path="x",
        ))


if __name__ == "__main__":
    unittest.main()
